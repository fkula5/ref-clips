#!/usr/bin/env bash
# Renders deploy/ref-clips.caddy for the shared edge proxy: replaces the {$REFCLIPS_SITE} and
# {$REFCLIPS_REDIRECT_HOSTS} placeholders with the values from .env and prints the result.
# The edge Caddy has no access to ref-clips' .env, so Caddy's own {$VAR} expansion cannot be used.
#
# Usage: deploy/render-site.sh TEMPLATE ENV_FILE
# Exit codes: 0 ok, 1 invalid or missing value, 2 usage.
set -euo pipefail

HOST_RE='^[A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?(\.[A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?)*$'

valid_host() {
  [ "${#1}" -le 253 ] && [[ "$1" =~ $HOST_RE ]]
}

# Last assignment of $2 in the env file, without surrounding whitespace, CR and one pair of quotes.
# .env is only parsed, never sourced.
env_value() {
  local v
  v="$(sed -n "s/^$2=//p" "$1" | tail -n1 | tr -d '\r')"
  v="${v#"${v%%[![:space:]]*}"}"; v="${v%"${v##*[![:space:]]}"}"
  case "$v" in
    \"*\") v="${v#\"}"; v="${v%\"}" ;;
    \'*\') v="${v#\'}"; v="${v%\'}" ;;
  esac
  printf '%s' "$v"
}

# render_site TEMPLATE SITE REDIRECT_HOSTS (space-separated, may be empty)
render_site() {
  local template="$1" site="$2" hosts="$3" content host redirect="" word
  [ -f "$template" ] || { echo "render-site: brak szablonu $template" >&2; return 1; }
  valid_host "$site" || { echo "render-site: nieprawidłowe REFCLIPS_SITE: '${site//[^[:print:]]/?}'" >&2; return 1; }
  # Split on spaces only: any other whitespace or control character stays in the word and fails the check.
  local IFS=' '
  set -f  # no globbing of the unquoted split below
  for word in $hosts; do
    valid_host "$word" || { set +f; echo "render-site: nieprawidłowy host w REFCLIPS_REDIRECT_HOSTS: '${word//[^[:print:]]/?}'" >&2; return 1; }
    redirect+=" $word"
  done
  set +f
  content="$(cat "$template"; printf x)"; content="${content%x}"
  # The leading space of the optional placeholder goes with it, so an empty value leaves no double space.
  content="${content// '{$REFCLIPS_REDIRECT_HOSTS}'/$redirect}"
  content="${content//'{$REFCLIPS_SITE}'/$site}"
  if [[ "$content" == *'{$REFCLIPS_'* ]]; then
    echo "render-site: w szablonie został nierozwiązany znacznik {\$REFCLIPS_...}" >&2
    return 1
  fi
  printf '# Generated by deploy/render-site.sh from deploy/ref-clips.caddy; do not edit, the next deploy overwrites it.\n%s' "$content"
}

main() {
  [ "$#" -eq 2 ] || { echo "Użycie: $0 SZABLON PLIK_ENV" >&2; return 2; }
  [ -f "$2" ] || { echo "render-site: brak pliku $2" >&2; return 1; }
  render_site "$1" "$(env_value "$2" REFCLIPS_SITE)" "$(env_value "$2" REFCLIPS_REDIRECT_HOSTS)"
}

[ "${BASH_SOURCE[0]}" != "$0" ] || main "$@"
